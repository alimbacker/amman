// Generates apps/mobile/lib/i18n_strings.dart from packages/shared/src/i18n.ts so the
// Flutter app and the website always use identical Tamil/English text.
// Run: node --experimental-strip-types scripts/gen-dart-i18n.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { strings, errorMessages } = await import(pathToFileURL(join(root, 'packages/shared/src/i18n.ts')).href);
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;
const block = (obj) => Object.entries(obj).map(([k, v]) => `  ${q(k)}: {'ta': ${q(v.ta)}, 'en': ${q(v.en)}},`).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-dart-i18n.mjs from packages/shared/src/i18n.ts — do not edit.
// ignore_for_file: lines_longer_than_80_chars

const Map<String, Map<String, String>> kStrings = {
${block(strings)}
};

const Map<String, Map<String, String>> kErrorMessages = {
${block(errorMessages)}
};
`;
writeFileSync(join(root, 'apps/mobile/lib/i18n_strings.dart'), out);
console.log(`wrote ${Object.keys(strings).length} strings, ${Object.keys(errorMessages).length} errors`);
